#!/usr/bin/env python3
"""Generate inventory + host_vars for a new workstation from setup.local.yml.

Reads the fill-in file (setup.local.yml, gitignored; see setup.yml.example),
writes ansible/inventory/host_vars/<inventory_host>.yml and adds the host
entry to ansible/inventory/hosts.yml. It never runs provisioning by itself
and never touches the existing desktop/laptop entries.

Usage:
    python3 scripts/setup-workstation.py            # generate from setup.local.yml
    python3 scripts/setup-workstation.py --file X   # use another data file
    python3 scripts/setup-workstation.py --verify   # run read-only Ansible checks
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required (comes with ansible-core / python3-yaml).")

ROOT = Path(__file__).resolve().parent.parent
HOSTS_YML = ROOT / "ansible" / "inventory" / "hosts.yml"
HOSTVARS_DIR = ROOT / "ansible" / "inventory" / "host_vars"
DEFAULT_DATA = ROOT / "setup.local.yml"

GENERATED_MARKER = "# Generated by scripts/setup-workstation.py from setup.local.yml"
RESERVED_HOSTS = {"desktop", "laptop"}
RESERVED_KEYS = {
    "workstation_device_class",
    "workstation_device_name",
    "workstation_syncthing_enabled",
    "workstation_backup_enabled",
    "workstation_backup_timer_enabled",
}
INVENTORY_HOST_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")
HOSTNAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9.-]*$")

HOST_ENTRY = (
    "        @HOST@:\n"
    "          ansible_connection: local\n"
    "          ansible_host: localhost\n"
    '          ansible_python_interpreter: "{{ ansible_playbook_python }}"\n'
    "\n"
)


def load_data(path: Path) -> dict:
    if not path.is_file():
        sys.exit(
            f"ERROR: {path} not found.\n"
            "Copy the template and fill it in:\n"
            "  cp setup.yml.example setup.local.yml\n"
            "  $EDITOR setup.local.yml\n"
            "  python3 scripts/setup-workstation.py"
        )
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        sys.exit(f"ERROR: {path} must contain a YAML mapping.")

    host = str(data.get("inventory_host", "")).strip()
    hostname = str(data.get("hostname", "")).strip()
    device_class = str(data.get("device_class", "")).strip()

    if not INVENTORY_HOST_RE.match(host):
        sys.exit("ERROR: inventory_host must start with a letter/digit and contain only letters, digits, '_' and '-'.")
    if host in RESERVED_HOSTS:
        sys.exit(f"ERROR: '{host}' is reserved for the maintainer's hosts; choose another inventory_host.")
    if not HOSTNAME_RE.match(hostname):
        sys.exit("ERROR: hostname must be a valid hostname (letters, digits, dots, dashes).")
    # Machine identity must be unique across the inventory (the playbook also
    # asserts this at provisioning time); fail early here with a clear message.
    for hv in sorted(HOSTVARS_DIR.glob("*.yml")):
        if hv.name.endswith(".example"):
            continue
        try:
            existing = yaml.safe_load(hv.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError:
            continue
        if isinstance(existing, dict) and existing.get("workstation_device_name") == hostname:
            sys.exit(f"ERROR: hostname '{hostname}' is already declared by {hv.name}; "
                     "each machine needs a unique workstation_device_name.")
    if device_class not in ("desktop", "laptop"):
        sys.exit("ERROR: device_class must be 'desktop' or 'laptop'.")

    profile = str(data.get("profile", "developer_gnome")).strip()
    if not re.match(r"^[A-Za-z0-9_-]+$", profile):
        sys.exit("ERROR: profile must contain only letters, digits, '_' and '-'.")
    profiles_dir = ROOT / "profiles"
    available = sorted(p.stem for p in profiles_dir.glob("*.yml")) if profiles_dir.is_dir() else []
    if profile not in available:
        sys.exit(f"ERROR: unknown profile '{profile}'. Available: {', '.join(available) or 'none'} "
                 f"(add profiles/{profile}.yml — see docs/DEPLOY.md section 8 and CONTRIBUTING.md).")
    data["profile"] = profile

    data["inventory_host"] = host
    data["hostname"] = hostname
    data["device_class"] = device_class
    data["workstation_profile"] = profile
    data.setdefault("syncthing_enabled", True)
    data.setdefault("backup_enabled", True)
    data.setdefault("backup_timer_enabled", False)
    for key in ("syncthing_enabled", "backup_enabled", "backup_timer_enabled"):
        if not isinstance(data[key], bool):
            sys.exit(f"ERROR: {key} must be true or false.")

    passthrough = {k: v for k, v in data.items() if k.startswith("workstation_")}
    # `profile` is mapped to workstation_profile above; drop the friendly key.
    data.pop("profile", None)
    clash = sorted(set(passthrough) & RESERVED_KEYS)
    if clash:
        sys.exit(f"ERROR: do not set {', '.join(clash)} directly; use the friendly names at the top of the file.")
    data["_passthrough"] = passthrough
    return data


def render_host_vars(data: dict) -> str:
    lines = [
        "---",
        GENERATED_MARKER,
        "# Re-run scripts/setup-workstation.py after editing setup.local.yml.",
        "",
        f"workstation_device_class: {data['device_class']}",
        f"workstation_device_name: {data['hostname']}",
        f"workstation_syncthing_enabled: {str(data['syncthing_enabled']).lower()}",
        f"workstation_backup_enabled: {str(data['backup_enabled']).lower()}",
        f"workstation_backup_timer_enabled: {str(data['backup_timer_enabled']).lower()}",
    ]
    for key in sorted(data["_passthrough"]):
        lines.append(f"{key}: {json.dumps(data['_passthrough'][key])}")
    lines.append("")
    return "\n".join(lines)


def write_host_vars(host: str, content: str) -> bool:
    HOSTVARS_DIR.mkdir(parents=True, exist_ok=True)
    path = HOSTVARS_DIR / f"{host}.yml"
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if GENERATED_MARKER not in existing:
            sys.exit(f"ERROR: {path} exists and was not generated by this script; rename or remove it manually first.")
        if existing == content:
            return False
    path.write_text(content, encoding="utf-8")
    return True


def ensure_host_entry(host: str) -> bool:
    text = HOSTS_YML.read_text(encoding="utf-8")
    if re.search(rf"(?m)^\s*{re.escape(host)}:\s*$", text):
        return False
    m = re.search(r"(?m)^(    workstations:\n      hosts:\n)", text)
    if not m:
        sys.exit("ERROR: unexpected hosts.yml structure; add the host entry manually:\n" + HOST_ENTRY.replace("@HOST@", host))
    new_text = text[: m.end()] + HOST_ENTRY.replace("@HOST@", host) + text[m.end():]
    yaml.safe_load(new_text)  # refuse to write invalid YAML
    HOSTS_YML.write_text(new_text, encoding="utf-8")
    return True


def verify(host: str) -> int:
    ansible_dir = ROOT / "ansible"
    checks = [
        ["ansible-playbook", "playbooks/workstation.yml", "--syntax-check"],
        ["ansible-playbook", "playbooks/validate-workstation.yml", "--syntax-check"],
        ["ansible-inventory", "-i", "inventory/hosts.yml", "--host", host],
    ]
    failed = 0
    for cmd in checks:
        print(f"\n$ {' '.join(cmd)}")
        result = subprocess.run(cmd, cwd=ansible_dir, check=False)
        if result.returncode != 0:
            failed += 1
    print(f"\nverify: {'PASS' if failed == 0 else 'FAIL'} ({failed} failed checks)")
    return 1 if failed else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--file", type=Path, default=DEFAULT_DATA,
                        help="data file to read (default: setup.local.yml)")
    parser.add_argument("--verify", action="store_true",
                        help="run read-only Ansible checks after generating (syntax-check + inventory)")
    args = parser.parse_args()

    data = load_data(args.file)
    host = data["inventory_host"]

    changed_vars = write_host_vars(host, render_host_vars(data))
    changed_hosts = ensure_host_entry(host)

    print(f"inventory host : {host}")
    print(f"profile        : {data['workstation_profile']}")
    print(f"hostname       : {data['hostname']} ({data['device_class']})")
    print(f"host_vars      : {'updated' if changed_vars else 'unchanged'} "
          f"({HOSTVARS_DIR / (host + '.yml')})")
    print(f"hosts.yml      : {'entry added' if changed_hosts else 'entry already present'} ({HOSTS_YML})")
    print()
    print("Next steps (run from your logged-in desktop session):")
    print(f"  cd {ROOT / 'ansible'}")
    print("  ansible-playbook playbooks/workstation.yml --syntax-check")
    print(f"  ansible-playbook playbooks/workstation.yml --check --diff -K --limit {host}")
    print("  # review the preview, then apply for real:")
    print(f"  ansible-playbook playbooks/workstation.yml -K --limit {host}")
    print(f"  ansible-playbook playbooks/validate-workstation.yml -e audit_enforce=true --limit {host}")
    print(f"  ansible-playbook playbooks/workstation.yml -K --limit {host}   # idempotency: changed=0")
    print()
    print("Manual enrollment still required: Proton sign-in, Syncthing pairing as a new")
    print("device, and pre-creating /my-files/Workstation-Backups/" + data["hostname"])
    print("in Proton Drive before enabling the backup timer (docs/WORKSTATION-INSTALL.md).")
    print("Keep setup.local.yml out of Git — it is gitignored; never put credentials in it.")

    if args.verify:
        return verify(host)
    return 0


if __name__ == "__main__":
    sys.exit(main())
